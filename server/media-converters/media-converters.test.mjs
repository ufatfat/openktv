import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import test from "node:test";
import { createQmcDecodeConverter } from "./plugins/qmcdecode.mjs";
import { MediaConverterRegistry } from "./registry.mjs";
import { createMapCipher, createRc4Cipher, createStaticCipher, decodeQmcFile, deriveMasterKey, lookupQmcEkey, parseQmcFooter } from "./vendor/qmc-codec.mjs";

function fixture() {
  const root = mkdtempSync(join(tmpdir(), "openktv-converters-"));
  const mediaDir = join(root, "media");
  mkdirSync(mediaDir);
  return { root, mediaDir, cleanup: () => rmSync(root, { recursive: true, force: true }) };
}

test("registers the cross-platform QMC formats without an external helper", () => {
  const registry = new MediaConverterRegistry([createQmcDecodeConverter()]);
  const [plugin] = registry.manifest();
  assert.equal(plugin.id, "qmcdecode");
  assert.equal(plugin.name, "QMC 跨平台转换");
  assert.equal(plugin.available, true);
  assert.equal(plugin.extensions.includes(".qmcflac"), true);
  assert.equal(plugin.extensions.includes(".mflac"), true);
  assert.equal(plugin.extensions.includes(".mgg1"), true);
  assert.equal(plugin.extensions.includes(".mggl"), true);
  assert.equal(plugin.extensions.includes(".qmc8"), true);
  assert.equal(plugin.extensions.includes(".bkcwma"), true);
  assert.deepEqual(plugin.outputs, [".flac", ".mp3", ".ogg", ".m4a", ".wav"]);
});

test("sniffs the decoded container for ambiguous qmc extensions", () => {
  const { mediaDir, cleanup } = fixture();
  try {
    const plaintext = Buffer.concat([Buffer.from("ID3"), Buffer.alloc(4093, 0x5a)]);
    const sourcePath = join(mediaDir, "ambiguous.qmc4");
    writeFileSync(sourcePath, createStaticCipher().decrypt(plaintext));
    const registry = new MediaConverterRegistry([createQmcDecodeConverter()]);
    const result = registry.convertDirectory(mediaDir);
    assert.equal(result.converted, 1);
    assert.equal(result.results[0].outputPath, join(mediaDir, "ambiguous.mp3"));
    assert.deepEqual(readFileSync(join(mediaDir, "ambiguous.mp3")), plaintext);
  } finally { cleanup(); }
});

test("parses MusicEx metadata without mistaking it for an embedded key", () => {
  const prefix = Buffer.alloc(12);
  const inner = Buffer.alloc(176);
  inner.write("001CVTzm3UeNdz", 12, "utf16le");
  inner.write("O4M0000sdLYV13MD0i.mgg", 72, "utf16le");
  const length = Buffer.alloc(4);
  const version = Buffer.alloc(4);
  length.writeUInt32LE(0xc0);
  version.writeUInt32LE(1);
  const footer = parseQmcFooter(Buffer.concat([prefix, inner, length, version, Buffer.from("musicex\0")]));
  assert.equal(footer.kind, "MusicEx");
  assert.equal(footer.size, 204);
  assert.equal(footer.ekey, null);
  assert.equal(footer.mid, "001CVTzm3UeNdz");
  assert.equal(footer.mediaFilename, "O4M0000sdLYV13MD0i.mgg");
});

test("looks up MusicEx keys from an Android player_process_db", () => {
  const { root, cleanup } = fixture();
  try {
    const databasePath = join(root, "player_process_db");
    const database = new DatabaseSync(databasePath);
    database.exec("CREATE TABLE audio_file_ekey_table (file_path TEXT, ekey TEXT)");
    database.prepare("INSERT INTO audio_file_ekey_table VALUES (?, ?)").run("/qqmusic/O4M0000sdLYV13MD0i.mgg", "fixture-ekey");
    database.close();
    assert.equal(lookupQmcEkey(databasePath, "O4M0000sdLYV13MD0i.mgg"), "fixture-ekey");
  } finally { cleanup(); }
});

