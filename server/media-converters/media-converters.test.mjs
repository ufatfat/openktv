test("decodes a static-key QMC file and preserves the source", () => {
  const { mediaDir, cleanup } = fixture();
  try {
    const plaintext = Buffer.alloc(16 * 1024);
    plaintext.write("fLaC", 0, "ascii");
    for (let index = 4; index < plaintext.length; index += 1) plaintext[index] = (index * 29 + 17) & 0xff;
    const encrypted = createStaticCipher().decrypt(plaintext);
    assert.ok(encrypted.readUInt32LE(encrypted.length - 4) >= 0x300);
    const sourcePath = join(mediaDir, "测试歌曲.qmcflac");
    writeFileSync(sourcePath, encrypted);

    const registry = new MediaConverterRegistry([createQmcDecodeConverter()]);
    const result = registry.convertDirectory(mediaDir);
    assert.equal(result.converted, 1);
    assert.deepEqual(readFileSync(join(mediaDir, "测试歌曲.flac")), plaintext);
    assert.equal(existsSync(sourcePath), true);
  } finally { cleanup(); }
});

test("map and segmented RC4 ciphers decrypt consistently across chunks", () => {
  const plaintext = Buffer.alloc(24 * 1024);
  for (let index = 0; index < plaintext.length; index += 1) plaintext[index] = (index * 13 + 91) & 0xff;
  const keys = [
    { factory: createMapCipher, key: Buffer.alloc(256).map((_, index) => (index * 7 + 3) & 0xff) },
    { factory: createRc4Cipher, key: Buffer.alloc(512).map((_, index) => (index * 11 + 5) & 0xff) },
  ];
  for (const { factory, key } of keys) {
    const encrypted = factory(key).decrypt(plaintext, 0);
    const decoded = Buffer.alloc(plaintext.length);
    const chunkSize = 4093;
    for (let offset = 0; offset < encrypted.length; offset += chunkSize) {
      const chunk = encrypted.subarray(offset, Math.min(offset + chunkSize, encrypted.length));
      factory(key).decrypt(chunk, offset).copy(decoded, offset);
    }
    assert.deepEqual(decoded, plaintext);
  }
});

test("standalone QMC decoder writes to a new output path", () => {
  const { mediaDir, cleanup } = fixture();
  try {
    const plaintext = Buffer.concat([Buffer.from("OggS"), Buffer.alloc(4092, 0x5a)]);
    const encrypted = createStaticCipher().decrypt(plaintext);
    const sourcePath = join(mediaDir, "demo.qmc2");
    const outputPath = join(mediaDir, "demo.ogg");
    writeFileSync(sourcePath, encrypted);
    decodeQmcFile(sourcePath, outputPath, { chunkSize: 257 });
    assert.deepEqual(readFileSync(outputPath), plaintext);
  } finally { cleanup(); }
});

test("rejects invalid decoded media instead of publishing it", () => {
  const { mediaDir, cleanup } = fixture();
  try {
    const sourcePath = join(mediaDir, "unsupported.mgg");
    const outputPath = join(mediaDir, "unsupported.ogg");
    writeFileSync(sourcePath, "encrypted-fixture");
    const registry = new MediaConverterRegistry([createQmcDecodeConverter({
      decodeFile: (_source, temporaryOutput) => writeFileSync(temporaryOutput, "not-an-ogg"),
    })]);
    const result = registry.convertDirectory(mediaDir);
    assert.equal(result.converted, 0);
    assert.equal(result.failed, 1);
    assert.match(result.results[0].error, /不是有效的目标音频/);
    assert.equal(existsSync(outputPath), false);
    assert.equal(existsSync(sourcePath), true);
  } finally { cleanup(); }
});

test("does not silently skip an existing invalid output", () => {
  const { mediaDir, cleanup } = fixture();
  try {
    const sourcePath = join(mediaDir, "existing.mgg");
    const outputPath = join(mediaDir, "existing.ogg");
    writeFileSync(sourcePath, "encrypted-fixture");
    writeFileSync(outputPath, "invalid-existing-output");
    const registry = new MediaConverterRegistry([createQmcDecodeConverter()]);
    const result = registry.convertDirectory(mediaDir);
    assert.equal(result.skipped, 0);
    assert.equal(result.failed, 1);
    assert.match(result.results[0].error, /未覆盖/);
    assert.equal(readFileSync(outputPath, "utf8"), "invalid-existing-output");
  } finally { cleanup(); }
});
